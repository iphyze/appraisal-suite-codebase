export const resolveAppIcon = (icon, fallback = ChevronDown) => {
  if (typeof icon === 'function' || (typeof icon === 'object' && icon !== null)) {
    return icon;
  }

  if (typeof icon === 'string') {
    return APP_ICONS[icon.trim()] || fallback;
  }

  return fallback;
};

const AppIcon = ({
  icon,
  fallback = ChevronDown,
  size = 16,
  strokeWidth = APP_ICON_STROKE_WIDTH,
  className,
  ...props
}) => {
  const Icon = resolveAppIcon(icon, fallback);

  return (
    <Icon
      aria-hidden="true"
      focusable="false"
      size={size}
      strokeWidth={strokeWidth}
      className={className}
      {...props}
    />
  );
};

export default AppIcon;
